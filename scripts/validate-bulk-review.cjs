// Real desktop UI, IPC and worker. Only the native file picker is replaced.
const {app, BrowserWindow, dialog} = require('electron');
const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');
const root = path.resolve(__dirname, '..');
const output = path.join(root, 'outputs/bulk-review-check');
fs.mkdirSync(output, {recursive: true});
const storage = fs.mkdtempSync(path.join(output, 'userdata-'));
app.setPath('userData', storage);
app.disableHardwareAcceleration();
app.commandLine.appendSwitch('in-process-gpu');
const fixture = path.join(root, 'outputs/bulk-import-check/fixture.nrrd');
const invalid = path.join(output, 'invalid.nrrd');
fs.writeFileSync(invalid, 'Invalid test fixture');
dialog.showOpenDialog = async () => ({canceled: false, filePaths: [...Array(116).fill(fixture), invalid, invalid]});
require(path.join(process.env.EXMO_TEST_APP_ROOT || root, 'desktop/main.cjs'));
const delay = ms => new Promise(resolve => setTimeout(resolve, ms));
const deadline = setTimeout(() => { console.error('Timed out'); app.exit(1); }, 120000);
console.log('Waiting for app readiness');
(async () => {
  await app.whenReady();
  console.log('App ready');
  const win = BrowserWindow.getAllWindows()[0];
  win.setSize(1440, 960);
  const contents = win.webContents;
  contents.on('console-message', event => console.log('Renderer:', event.message));
  contents.on('did-fail-load', (_event, code, description) => console.error('Load failed:', code, description));
  if (contents.isLoading()) await new Promise(resolve => contents.once('did-finish-load', resolve));
  console.log('Renderer loaded:', contents.getURL());
  fs.writeFileSync(path.join(output, 'initial.png'), (await contents.capturePage()).toPNG());
  const run = fn => contents.executeJavaScript('(' + fn.toString() + ')()');
  const wait = async fn => {for(let i=0;i<400;i++){if(await run(fn))return;await delay(50)}throw new Error('UI timeout: '+fn)};
  await wait(() => document.querySelector('[aria-label="CT 허벅지 근육 분석"]'));
  await run(() => document.querySelector('[aria-label="CT 허벅지 근육 분석"]').click());
  await wait(() => [...document.querySelectorAll('button')].some(b => b.textContent.trim()==='영상 추가' && !b.disabled));
  await run(() => [...document.querySelectorAll('button')].find(b => b.textContent.trim()==='영상 추가').click());
  await wait(() => {
    const n = document.querySelectorAll('.series-table tbody tr').length;
    return n > 0 && n < 118 && document.querySelector('.import-status progress')?.value > 0;
  });
  const partial = await run(() => ({rows:document.querySelectorAll('.series-table tbody tr').length,text:document.querySelector('.import-status').textContent}));
  fs.writeFileSync(path.join(output, 'incremental.png'), (await contents.capturePage()).toPNG());
  await wait(() => document.querySelectorAll('.series-table tbody tr').length === 118 && !document.querySelector('.import-status'));
  await run(() => [...document.querySelectorAll('button')].find(b=>b.textContent.trim()==='선택 영상 검토' && !b.disabled).click());
  await wait(() => document.querySelectorAll('.review-case img').length===4);
  const first = await run(() => [...document.querySelectorAll('.review-case')].map(n=>({id:n.dataset.inputId,height:n.getBoundingClientRect().height})));
  assert.equal(first.length,4);
  assert.ok(first.every(n=>n.height>=400),'Review cards must not collapse');
  assert.ok(await run(()=>document.querySelector('.review-pagination').textContent.includes('116')));
  await run(()=>document.querySelector('.review-case .input-confirmation input').click());
  fs.writeFileSync(path.join(output, 'review-page-1.png'), (await contents.capturePage()).toPNG());
  await run(()=>[...document.querySelectorAll('button')].find(b=>b.textContent==='다음 페이지').click());
  await wait(()=>document.querySelectorAll('.review-case img').length===4);
  const second = await run(()=>[...document.querySelectorAll('.review-case')].map(n=>n.dataset.inputId));
  assert.ok(second.every(id=>!first.some(n=>n.id===id)));
  await run(()=>[...document.querySelectorAll('button')].find(b=>b.textContent==='이전 페이지').click());
  await wait(()=>document.querySelector('.review-case .input-confirmation input')?.checked);
  win.setSize(900, 660);
  await delay(300);
  assert.ok(await run(()=>[...document.querySelectorAll('.review-case')].every(n=>n.getBoundingClientRect().height>=400)));
  fs.writeFileSync(path.join(output, 'review-compact.png'), (await contents.capturePage()).toPNG());
  await run(()=>[...document.querySelectorAll('button')].find(b=>b.textContent==='분석 가능한 영상 전체 선택').click());
  assert.ok(await run(()=>document.querySelector('.review-batch-summary').textContent.includes('116개 전체')));
  await run(()=>document.querySelector('.review-batch-summary input').click());
  assert.ok(await run(()=>![...document.querySelectorAll('button')].find(b=>b.textContent==='Segmentation 실행').disabled));
  fs.writeFileSync(path.join(output, 'report.json'), JSON.stringify({passed:true,partial,registered:118,selected:116,renderedCards:4,minimumCardHeight:Math.min(...first.map(n=>n.height)),checks:['real progressive registration','real CT previews','pagination','confirmation retained','compact layout','full batch selection and confirmation']},null,2));
  clearTimeout(deadline);
  console.log('PASS: incremental registration and 116-image review UI');
  app.quit();
})().catch(error=>{console.error(error);clearTimeout(deadline);app.exit(1)});
