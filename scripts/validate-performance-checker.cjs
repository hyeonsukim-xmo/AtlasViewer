const assert = require('node:assert/strict');
const {stats,summarize,signature,compare,markdown} = require('./performance-desktop.cjs');
assert.deepEqual(stats([3,1,2]),{n:3,median:2,min:1,max:3,p95:3});
assert.equal(stats([1,4]).median,2.5);
assert.equal(stats([]),null);
assert.equal(summarize([{seconds:{ready:3}},{seconds:{ready:7,mesh:2}}]).mesh.n,1);
assert.equal(summarize([{repetition:1,seconds:{batchWall:10}},{repetition:1,seconds:{batchWall:10}},{repetition:2,seconds:{batchWall:14}}]).batchWall.n,2);
const check={maskPayloadSha256:'one',measurements:[{id:'muscle',count:10,value:1}],qc:{tta:'original'},overlays:{axial:{sha256:'image',seconds:1}}};
assert.deepEqual(signature(check),signature({...check,overlays:{axial:{sha256:'image',seconds:100}}}));
const report={schema:1,complete:true,passed:true,environment:{gpu:'same'},options:{device:'cuda:0',repeats:3,batchSize:1},cases:{
  ct:{identity:{input:'sample',model:'weights'},trials:[{execution:{precision:'float32'},check}],summary:{ready:{median:100},batchWall:{median:110}}}
}};
assert.equal(compare(report,structuredClone(report),15).passed,true);
const slower=structuredClone(report);slower.cases.ct.summary.ready.median=120;
assert.equal(compare(slower,report,15).passed,false);
const phase=structuredClone(report),phaseBefore=structuredClone(report);
phaseBefore.cases.ct.summary.inference=stats([10]);phase.cases.ct.summary.inference=stats([14]);
assert.equal(compare(phase,phaseBefore,15).passed,false,'Per-stage regressions must not hide behind unchanged totals');
const different=structuredClone(report);different.cases.ct.trials[0].check.maskPayloadSha256='changed';
assert.equal(compare(different,report,15).passed,false,'Faster output with different masks must fail');
different.cases.ct.trials[0].check=structuredClone(check);
different.cases.ct.trials[0].check.relatedMasks={pp500:{maskPayloadSha256:'changed'}};
assert.equal(compare(different,report,15).passed,false,'Generated PP500 must also remain identical');
different.cases.ct.trials[0].check=check;different.cases.ct.trials[0].execution.precision='float16';
assert.throws(()=>compare(different,report,15),/runtime/);
const incompatible=structuredClone(report);incompatible.environment.gpu='other';
assert.throws(()=>compare(incompatible,report,15),/Incompatible/);
const badBaseline=structuredClone(report);badBaseline.complete=false;
assert.throws(()=>compare(report,badBaseline,15),/completed/);
assert.throws(()=>compare(badBaseline,report,15),/incomplete/);
assert.throws(()=>markdown(report),TypeError,'Incomplete statistics must not be silently fabricated');
const detailed=structuredClone(report);detailed.cases.ct.summary={preprocessing:stats([1,2,3]),inference:stats([10,20,30]),verification:stats([4,5,6])};
const output=markdown(detailed);
assert(output.indexOf('Pipeline stages')<output.indexOf('Endpoints'));
assert(output.includes('Preprocessing | 2.00') && output.includes('readback verification | 5.00'));
const startup=structuredClone(detailed);
startup.cases.ct.trials[0].startupOperations={startup_torch:4,startup_monai:9};
const startupOutput=markdown(startup);
assert(startupOutput.includes('startup_monai | 9.00') && startupOutput.includes('do not add again'));
console.log('PASS: medians, missing stages, baseline compatibility, numerical and timing regressions');
