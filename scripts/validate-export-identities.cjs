const fs=require('node:fs/promises'),path=require('node:path'),assert=require('node:assert/strict');
const {createExportIdentities}=require('../desktop/export-identities.cjs');
(async()=>{
 const output=path.resolve(__dirname,'../outputs/export-identities-check');await fs.mkdir(output,{recursive:true});
 const store=await fs.mkdtemp(path.join(output,'registry-'));
 let registry=createExportIdentities(store);
 const input={inputId:'input-a',analysis:'ct',studyUid:'study-a',seriesUid:'series-a',patientId:'Anonymous'};
 const first=await registry.resolve(input);assert.equal(first.patientId,'');assert.match(first.uuid,/^[0-9a-f-]{36}$/);
 registry=createExportIdentities(store);
 assert.equal((await registry.resolve({...input,resultId:'result-a'})).uuid,first.uuid,'Restart and result export reuse identity');
 assert.equal((await registry.resolve({...input,inputId:'input-b',seriesUid:'series-b'})).uuid,first.uuid,'Same study links series');
 assert.notEqual((await registry.resolve({...input,inputId:'input-c',studyUid:'study-b'})).uuid,first.uuid,'Anonymous across studies never merges');
 const withoutStudy={inputId:'input-d',analysis:'ct'};
 assert.equal((await registry.resolve(withoutStudy)).uuid,(await registry.resolve({...withoutStudy,resultId:'result-d'})).uuid);
 assert.notEqual((await registry.resolve(withoutStudy)).uuid,(await registry.resolve({...withoutStudy,inputId:'input-e'})).uuid);
 const known={...input,patientId:'000123',patientIssuer:'hospital-A'};
 const linked=await registry.resolve(known);assert.equal(linked.uuid,first.uuid);assert.equal(linked.patientId,'000123');
 assert.equal((await registry.resolve({...known,inputId:'input-f',studyUid:'study-c'})).uuid,first.uuid,'Known issuer and patient ID link studies');
 assert.notEqual((await registry.resolve({...known,inputId:'input-g',studyUid:'study-d',patientIssuer:'hospital-B'})).uuid,first.uuid);
 assert.notEqual((await registry.resolve({...known,patientId:'000124'})).uuid,first.uuid,'Conflicting patient ID does not overwrite an identity');
 const concurrent=await Promise.all(Array.from({length:12},()=>registry.resolve({...known,resultId:'result-a'})));
 assert.ok(concurrent.every(row=>row.uuid===first.uuid));
 await registry.recordExport(linked,{...known,resultId:'result-a'},{action:'save',filename:'renamed,file.png',sha256:'abc'});
 await registry.resolve({inputId:'formula',analysis:'ct',patientId:'=SUM(1,2)',patientIssuer:'issuer'});
 const csv=await registry.csv();assert.ok(csv.startsWith('\uFEFF'));assert.match(csv,/"000123"/);assert.match(csv,/"renamed,file.png"/);assert.match(csv,/"'=SUM\(1,2\)"/);
 const table=JSON.parse(await fs.readFile(path.join(store,'export-identities.json'),'utf8'));
 assert.equal(table.exports.length,1);assert.equal(table.exports[0].uuid,first.uuid);
 assert.equal(table.identities.find(row=>row.uuid===first.uuid).patientId,'000123');
 await fs.writeFile(path.join(store,'export-identities.json'),'broken');
 await assert.rejects(registry.resolve(input),'Corrupt identity tables must never silently regenerate UUIDs');
 console.log('PASS: persistent UUIDs, study/input scopes, patient/issuer matching, leading zeros, conflicts, concurrency, CSV and corrupt-table protection');
})().catch(error=>{console.error(error);process.exitCode=1;});
