const fs=require('node:fs'),path=require('node:path'),os=require('node:os'),assert=require('node:assert/strict');
const {readNrrdMetadata,createSourceMetadata}=require('../desktop/source-metadata.cjs');
const root=fs.mkdtempSync(path.join(os.tmpdir(),'exmo-source-metadata-'));
const raw=path.join(root,'input.nrrd');
fs.writeFileSync(raw,'NRRD0005\r\n# comment\r\ntype: short\r\nDICOM_PatientID:=00042\r\nDICOM_StudyDate:=20251012\r\nDICOM_SeriesDescription:=Axial 5mm\r\n\r\nPatientID:=PIXEL_PAYLOAD');
assert.deepEqual(readNrrdMetadata(raw),{patientId:'00042',studyDate:'20251012',seriesDescription:'Axial 5mm'});
const input={id:'one',input:path.join(root,'validated-input.nii.gz'),analysis:'ct',metadata:{caseName:'long filename',format:'NRRD'}};
const store=createSourceMetadata(root);
assert.equal(store.apply(input).metadata.patientId,'00042','Validation must not lose retained-header identity');
assert.equal(store.apply({id:'result',inputId:'one',analysis:'ct',metadata:{caseName:'Anonymous'}},input).metadata.studyDate,'20251012');
assert.equal(input.metadata.patientId,undefined,'Catalog objects stay unchanged');
fs.writeFileSync(path.join(root,'source-metadata.json'),JSON.stringify({version:1,records:{dicom:{metadata:{patientId:'00099',studyDate:'20261006',input:'/untrusted'}}}}));
const recovered=createSourceMetadata(root).apply({id:'dicom',analysis:'ct',metadata:{format:'DICOM'}});
assert.equal(recovered.metadata.patientId,'00099');assert.equal(recovered.metadata.input,undefined);
const invalid=path.join(root,'invalid.nrrd');fs.writeFileSync(invalid,'NRRD0005\nDICOM_PatientID:=NO_HEADER_END');
assert.deepEqual(readNrrdMetadata(invalid),{});
fs.writeFileSync(invalid,'NRRD0005\nPatientID:=00123\nDICOM_PatientID:=other\n\n');
assert.equal(readNrrdMetadata(invalid).patientId,'00123');
const external=path.join(os.tmpdir(),`exmo-outside-${Date.now()}.nrrd`);fs.copyFileSync(raw,external);
assert.equal(createSourceMetadata(root).apply({id:'outside',input:external,analysis:'ct',metadata:{}}).metadata.patientId,undefined);
fs.unlinkSync(external);
console.log('PASS: prefixed/plain NRRD tags, leading zeros, payload boundary, retained input after validation, result projection, verified sidecar whitelist, private path boundary');
