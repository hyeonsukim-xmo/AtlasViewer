"""Private numerical checks for performance-desktop.cjs; no masks leave the local store."""
import argparse
import base64
import hashlib
import importlib.util
import json
from pathlib import Path
import time

import numpy as np
import SimpleITK as sitk

ROOT = Path(__file__).resolve().parents[1]


def check(publication, reference, worker, previous=None):
    image = sitk.ReadImage(publication["mask"])
    expected = sitk.ReadImage(str(reference))
    if not worker.same_geometry(image, expected):
        raise ValueError("Reference geometry differs")
    labels, baseline = sitk.GetArrayFromImage(image), sitk.GetArrayFromImage(expected)
    repeat_differences = None
    repeat_details = None
    if previous:
        previous_result = worker.read_json(previous)
        earlier = sitk.ReadImage(previous_result["mask"])
        if not worker.same_geometry(image, earlier): raise ValueError("Repeated geometry differs")
        old_labels = sitk.GetArrayViewFromImage(earlier)
        changed = labels != old_labels
        repeat_differences = int(np.count_nonzero(changed))
        old_rows = {row["id"]: row for row in previous_result["summary"]["rows"]}
        changes = [{"id": row["id"], "before": old_rows[row["id"]]["value"], "after": row["value"],
                    "delta": row["value"] - old_rows[row["id"]]["value"]} for row in publication["summary"]["rows"]]
        repeat_details = {"fractionOfFullImage": repeat_differences / labels.size,
                          "unit": publication["summary"]["unit"], "classMeasurements": changes,
                          "maxAbsoluteMeasurementDelta": max((abs(row["delta"]) for row in changes), default=0)}
        if publication["summary"]["analysis"] == "xray":
            # Mark both sides of each original four-neighbour class boundary.
            plane = old_labels[0]
            boundary = np.zeros(plane.shape, dtype=bool)
            horizontal, vertical = plane[:, 1:] != plane[:, :-1], plane[1:] != plane[:-1]
            boundary[:, 1:] |= horizontal; boundary[:, :-1] |= horizontal
            boundary[1:] |= vertical; boundary[:-1] |= vertical
            repeat_details["changedOutsideOriginalBoundary"] = int(np.count_nonzero(changed[0] & ~boundary))
    summary = publication["summary"]
    counts = np.bincount(labels.ravel().astype(np.int64))
    for row in summary["rows"]:
        count = int(counts[row["label"]]) if row["label"] < len(counts) else 0
        if row["count"] != count or not np.isfinite(row["value"]) or row["value"] < 0:
            raise ValueError("Invalid native measurement")
        if row.get("sides") and sum(row["sides"][side]["count"] for side in ("left", "right", "unassigned")) != count:
            raise ValueError("Laterality lost native voxels")
    geometry = {"size": image.GetSize(), "spacing": image.GetSpacing(),
                "origin": image.GetOrigin(), "direction": image.GetDirection()}
    fingerprint = hashlib.sha256(json.dumps(geometry, sort_keys=True).encode())
    fingerprint.update(labels.astype("<u2").tobytes())
    related = {}
    if summary["analysis"] == "mri":
        # PP500 is generated by the same model run; verify it even when Raw is displayed.
        folder = Path(publication["result"]) / "pp500"
        processed = sitk.ReadImage(str(folder / "mask.nrrd"))
        if not worker.same_geometry(image, processed): raise ValueError("PP500 geometry differs")
        values = sitk.GetArrayFromImage(processed)
        counts_pp = np.bincount(values.ravel().astype(np.int64))
        metrics = worker.read_json(folder / "metrics.json")["classes"]
        voxel_ml = abs(np.linalg.det(np.array(processed.GetDirection()).reshape(3, 3))) * np.prod(processed.GetSpacing()) / 1000
        selected = []
        for row in metrics:
            label = row["label_id"]
            count = int(counts_pp[label]) if label < len(counts_pp) else 0
            if row["voxel_count"] != count or not np.isclose(row["volume_ml"], count * voxel_ml, rtol=1e-5, atol=1e-5):
                raise ValueError("Invalid PP500 native measurement")
            selected.append({key: row.get(key) for key in ("label_id", "voxel_count", "volume_ml", "mean_entropy")})
        related["pp500"] = {"maskPayloadSha256": hashlib.sha256(values.astype("<u2").tobytes()).hexdigest(), "measurements": selected}
    views = ("axial",) if summary["analysis"] == "xray" else ("axial", "coronal", "sagittal")
    overlay = {}
    for view in views:
        started = time.perf_counter()
        preview = worker.preview({"record": publication["record"], "mask": publication["mask"],
                                  "sideMask": publication.get("sideMask"), "rows": summary["rows"], "view": view})
        payload = base64.b64decode(preview["image"].split(",", 1)[1])
        if not payload.startswith(b"\x89PNG\r\n\x1a\n"):
            raise ValueError("Invalid Overlay PNG")
        overlay[view] = {"seconds": time.perf_counter() - started, "sha256": hashlib.sha256(payload).hexdigest()}
    if summary["analysis"] != "xray":
        if summary.get("meshState") != "ready" or not publication.get("mesh"):
            raise ValueError("3D did not complete")
        with Path(publication["mesh"]).open("rb") as stream:
            if stream.read(4) != b"glTF": raise ValueError("Invalid GLB")
    return {"maskPayloadSha256": fingerprint.hexdigest(), "geometry": geometry, "relatedMasks": related,
            "measurements": [{key: row.get(key) for key in ("id", "count", "value", "fat", "hu", "entropy", "sides")} for row in summary["rows"]],
            "qc": summary["qc"], "overlays": overlay,
            "referenceDifferences": int(np.count_nonzero(labels != baseline)),
            "repeatDifferences": repeat_differences, "repeatDetails": repeat_details, "voxels": int(labels.size),
            "meshBytes": summary.get("meshBytes"), "unit": summary["unit"]}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--publication", type=Path, required=True)
    parser.add_argument("--reference", type=Path, required=True)
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--previous", type=Path, help="Earlier publication from the same repeated case")
    args = parser.parse_args()
    spec = importlib.util.spec_from_file_location("imaging_worker", ROOT / "desktop/imaging-worker.py")
    worker = importlib.util.module_from_spec(spec); spec.loader.exec_module(worker)
    publication = worker.read_json(args.publication)
    # Checks run AFTER the timed desktop job, so reference reads don't distort latency.
    report = check(publication, args.reference, worker, args.previous)
    args.output.write_text(json.dumps(report, indent=2), encoding="utf8")
    print("PASS: native metrics, geometry, three-view Overlay and expected 3D output", flush=True)


if __name__ == "__main__": main()
