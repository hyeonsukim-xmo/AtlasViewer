// Real renderer + preload; deterministic IPC fixtures, no patient files or inference.
const {app, BrowserWindow, ipcMain} = require('electron');
const fs = require('node:fs'), path = require('node:path'), assert = require('node:assert/strict');
const root = path.resolve(__dirname, '..');
const output = path.join(root, 'outputs/review-selection-check');
fs.mkdirSync(output, {recursive:true});
app.setPath('userData', fs.mkdtempSync(path.join(output, 'userdata-')));
const metadata={caseName:'Fixture',studyDescription:'Selection test',seriesDescription:'CT fixture',format:'NRRD',size:[16,16,16],spacing:[1,1,1],slices:16};
const files=Array.from({length:6},(_,i)=>({id:`fixture-${i}`,name:`Image ${i}`,analysis:'ct',ready:true,warnings:[],metadata,confirmation:i===0?'hu':undefined}));
const calls=[];
const original=ipcMain.handle.bind(ipcMain);
ipcMain.handle=(channel,handler)=>original(channel,async(event,...args)=>{
 const operation=channel.replace('exmo:imaging:','');
 let value;
 if(operation==='status')value={reviewAvailable:true,estimationAvailable:true,device:'CPU'};
 else if(operation==='list')value=['ct','exmo.thigh.ct'].includes(args[0])?files:[];
 else if(operation==='results')value=[];
 else if(operation==='job')value=null;
 else if(operation==='run'){calls.push(args);value=null;}
 else if(operation==='preview')value={image:'data:image/png;base64,iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+aX1cAAAAASUVORK5CYII=',index:8,count:16,view:args[2]?.view||'axial',sides:['R','L','A','P'],metadata,warnings:[]};
 else return handler(event,...args);
 return {ok:true,value};
});
require(path.join(root,'desktop/main.cjs'));
const delay=ms=>new Promise(r=>setTimeout(r,ms));
const deadline=setTimeout(()=>app.exit(1),60000);
(async()=>{
 await app.whenReady();
 const win=BrowserWindow.getAllWindows()[0]; win.hide();
 const wc=win.webContents;
 if(wc.isLoading())await new Promise(r=>wc.once('did-finish-load',r));
 const run=fn=>wc.executeJavaScript(`(${fn})()`);
 const wait=async fn=>{for(let i=0;i<100;i++){if(await run(fn))return;await delay(50);}throw Error('UI timeout: '+fn);};
 await wait(()=>document.querySelector('button[aria-label="CT 허벅지 근육 분석"]'));
 await run(()=>document.querySelector('button[aria-label="CT 허벅지 근육 분석"]').click());
 await wait(()=>document.querySelectorAll('.series-table tbody tr[data-input-id] input').length===6);
 await run(()=>[...document.querySelectorAll('.series-table tbody tr[data-input-id] input')].slice(0,5).forEach(e=>e.click()));
 await run(()=>[...document.querySelectorAll('button')].find(b=>b.textContent==='선택 영상 검토'&&!b.disabled).click());
 await wait(()=>document.querySelectorAll('.review-run-selection input').length===4);
 assert.ok(await run(()=>[...document.querySelectorAll('button')].find(b=>b.textContent.startsWith('Segmentation 실행')).disabled));
 await run(()=>document.querySelector('.review-run-selection input').click());
 assert.ok(await run(()=>[...document.querySelectorAll('button')].find(b=>b.textContent.startsWith('Segmentation 실행')).disabled),'HU gate remains enforced');
 await run(()=>document.querySelector('.review-case .input-confirmation input').click());
 assert.ok(await run(()=>document.querySelector('.review-run-selection input').checked),'HU checkbox must not toggle selection');
 await run(()=>document.querySelector('.review-case .preview-toolbar button:nth-child(2)').click());
 assert.ok(await run(()=>document.querySelector('.review-run-selection input').checked),'View controls must not toggle selection');
 await run(()=>document.querySelector('.review-case .medical-image').click());
 assert.equal(await run(()=>document.querySelectorAll('.review-case').length),4,'Deselection keeps cards visible');
 assert.ok(await run(()=>!document.querySelector('.review-run-selection input').checked));
 await run(()=>document.querySelector('.review-case .medical-image').click());
 await run(()=>[...document.querySelectorAll('button')].find(b=>b.textContent==='다음 페이지').click());
 await wait(()=>document.querySelector('.review-case')?.dataset.inputId==='fixture-4');
 await run(()=>document.querySelector('.review-run-selection input').click());
 await run(()=>[...document.querySelectorAll('button')].find(b=>b.textContent==='이전 페이지').click());
 await wait(()=>document.querySelector('.review-run-selection input')?.checked);
 await run(()=>[...document.querySelectorAll('button')].find(b=>b.textContent.startsWith('Segmentation 실행')).click());
 await delay(100);
 assert.deepEqual(calls[0][1],['fixture-0','fixture-4'],'Only checked IDs across pages reach run IPC');
 await run(()=>[...document.querySelectorAll('button')].find(b=>b.textContent==='분석 선택 모두 해제').click());
 assert.ok(await run(()=>[...document.querySelectorAll('button')].find(b=>b.textContent.startsWith('Segmentation 실행')).disabled));
 await run(()=>[...document.querySelectorAll('button')].find(b=>b.textContent==='검토 영상 전체 선택').click());
 await run(()=>[...document.querySelectorAll('button')].find(b=>b.textContent.startsWith('Segmentation 실행')).click());
 await delay(100);
 assert.deepEqual(calls[1][1],files.slice(0,5).map(f=>f.id),'Select all never pulls in unreviewed library items');
 assert(calls.every(call=>call[0]==='exmo.thigh.ct'),'New runs carry the selected solution ID');
 fs.writeFileSync(path.join(output,'report.json'),JSON.stringify({passed:true,submittedIds:calls.map(call=>call[1])},null,2));
 console.log('PASS: explicit selection, deselection retains cards, controls isolated, HU gate, pagination persistence, exact run IDs, scoped select-all, clear selection');
 clearTimeout(deadline);app.quit();
})().catch(e=>{console.error(e);clearTimeout(deadline);app.exit(1);});
